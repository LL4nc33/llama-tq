#!/usr/bin/env python3

from glob import glob
import os

HEAD_SIZES_KQ = [40, 64, 72, 80, 96, 112, 128, 192, 256, 320, 512, 576]

# DKQ -> DV override for asymmetric head dims.
HEAD_SIZES_V_OVERRIDE = {576: 512, 320: 256, 192: 128}

TYPES_KV = ["GGML_TYPE_F16", "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0", "GGML_TYPE_BF16"]

# TurboQuant cache types. KTQ types can be K or V, VTQ types are V only.
# Every pair with a TurboQuant side also gets head size 512 (Gemma 4 global attention), in a file of its own
# because it is the most expensive instantiation. The dispatch TUs (fattn-vec-dispatch-*.cu) only reference
# these instances (extern declarations in fattn-vec.cuh), so every pair compiles in its own TU, in parallel.
TYPES_KTQ = ["GGML_TYPE_KTQ1_1", "GGML_TYPE_KTQ2_1", "GGML_TYPE_KTQ3_1", "GGML_TYPE_KTQ4_1"]
TYPES_VTQ = [
    "GGML_TYPE_VTQ1_1", "GGML_TYPE_VTQ2_1", "GGML_TYPE_VTQ3_1", "GGML_TYPE_VTQ4_1",
    "GGML_TYPE_VTQ2_2", "GGML_TYPE_VTQ3_2", "GGML_TYPE_VTQ4_2",
    "GGML_TYPE_VTQ2_2S", "GGML_TYPE_VTQ3_2S", "GGML_TYPE_VTQ4_2S",
    "GGML_TYPE_VTQ2_3", "GGML_TYPE_VTQ3_3", "GGML_TYPE_VTQ4_3", "GGML_TYPE_VTQ3_V8",
]
TYPES_VEC_K = TYPES_KV + TYPES_KTQ
TYPES_VEC_V = TYPES_KV + TYPES_KTQ + TYPES_VTQ

# Trellis K cache types: K only, head sizes 128 and 256 (multiples of the 128-value block), next to a few V types.
TYPES_KTQ_TRELLIS = ["GGML_TYPE_KTQ2_3S", "GGML_TYPE_KTQ3_3S", "GGML_TYPE_KTQ4_3S"]
TYPES_KTQ_TRELLIS_V = [
    "GGML_TYPE_F16", "GGML_TYPE_VTQ2_1", "GGML_TYPE_VTQ3_1", "GGML_TYPE_VTQ4_1",
    "GGML_TYPE_VTQ2_2S", "GGML_TYPE_VTQ3_2S", "GGML_TYPE_VTQ4_2S",
]

SOURCE_FATTN_TILE = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-tile.cuh"

DECL_FATTN_TILE_CASE({head_size_kq}, {head_size_v});
"""

SOURCE_FATTN_VEC = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec.cuh"

DECL_FATTN_VEC_CASE( 64, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(128, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(256, {type_k}, {type_v});
"""

SOURCE_FATTN_VEC_TRELLIS_K = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec.cuh"

DECL_FATTN_VEC_CASE(128, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(256, {type_k}, {type_v});
"""

SOURCE_FATTN_VEC_D512 = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec.cuh"

DECL_FATTN_VEC_CASE(512, {type_k}, {type_v});
"""

SOURCE_FATTN_VEC_GQA = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec-gqa.cuh"

DECL_FATTN_VEC_GQA_CASE({head_size}, {ncols}, {type_k});
"""

SOURCE_FATTN_TQ_WMMA = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-tq-wmma.cuh"

DECL_FATTN_TQ_WMMA_CASE({head_size}, {ncols});
"""

SOURCE_FATTN_MMA_START = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-mma-f16.cuh"

"""

SOURCE_FATTN_MMA_CASE = "DECL_FATTN_MMA_F16_CASE({head_size_kq}, {head_size_v}, {ncols1}, {ncols2});\n"

TYPES_MMQ = [
    "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0",
    "GGML_TYPE_Q2_K", "GGML_TYPE_Q3_K", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q6_K",
    "GGML_TYPE_IQ2_XXS", "GGML_TYPE_IQ2_XS", "GGML_TYPE_IQ2_S", "GGML_TYPE_IQ3_XXS", "GGML_TYPE_IQ3_S",
    "GGML_TYPE_IQ1_S", "GGML_TYPE_IQ4_NL", "GGML_TYPE_IQ4_XS", "GGML_TYPE_MXFP4", "GGML_TYPE_NVFP4",
    "GGML_TYPE_PQ2_0", "GGML_TYPE_PTQ1_0"
]

SOURCE_MMQ = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmq.cuh"

DECL_MMQ_CASE({type});
"""

SOURCE_MMF = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmf.cuh"

DECL_MMF_CASE({type});
"""


def get_short_name(long_quant_name):
    return long_quant_name.replace("GGML_TYPE_", "").lower()


for filename in glob("*.cu"):
    os.remove(filename)

for head_size_kq in HEAD_SIZES_KQ:
    head_size_v = HEAD_SIZES_V_OVERRIDE.get(head_size_kq, head_size_kq)
    with open(f"fattn-tile-instance-dkq{head_size_kq}-dv{head_size_v}.cu", "w") as f:
        f.write(SOURCE_FATTN_TILE.format(head_size_kq=head_size_kq, head_size_v=head_size_v))

for type_k in TYPES_VEC_K:
    for type_v in TYPES_VEC_V:
        name = f"fattn-vec-instance-{get_short_name(type_k)}-{get_short_name(type_v)}"
        with open(f"{name}.cu", "w") as f:
            f.write(SOURCE_FATTN_VEC.format(type_k=type_k, type_v=type_v))
        if type_k in TYPES_KV and type_v in TYPES_KV:
            continue
        with open(f"{name}-d512.cu", "w") as f:
            f.write(SOURCE_FATTN_VEC_D512.format(type_k=type_k, type_v=type_v))

for type_k in TYPES_KTQ_TRELLIS:
    for type_v in TYPES_KTQ_TRELLIS_V:
        with open(f"fattn-vec-instance-{get_short_name(type_k)}-{get_short_name(type_v)}.cu", "w") as f:
            f.write(SOURCE_FATTN_VEC_TRELLIS_K.format(type_k=type_k, type_v=type_v))

# GQA decode kernel for quantized caches (fattn-vec-gqa.cuh): one TU per head size, block width and K type
TYPES_GQA_K = ["GGML_TYPE_F16", "GGML_TYPE_Q8_0", "GGML_TYPE_Q5_0", "GGML_TYPE_Q4_0"] + TYPES_KTQ[1:] + TYPES_KTQ_TRELLIS
for head_size in [128, 256]:
    for ncols in [4, 8]:
        for type_k in TYPES_GQA_K:
            with open(f"fattn-gqa-instance-d{head_size}-ncols{ncols}-{get_short_name(type_k)}.cu", "w") as f:
                f.write(SOURCE_FATTN_VEC_GQA.format(head_size=head_size, ncols=ncols, type_k=type_k))

# tensor-core kernel for quantized caches (fattn-tq-wmma.cuh): one TU per head size and block width
# (32 columns for small batches of queries, not at head 512)
TQ_WMMA_CASES = [(64, 16), (64, 32), (128, 16), (128, 32), (256, 16), (256, 32), (512, 16)]
for head_size, ncols in TQ_WMMA_CASES:
    with open(f"fattn-tq-wmma-instance-d{head_size}-ncols{ncols}.cu", "w") as f:
        f.write(SOURCE_FATTN_TQ_WMMA.format(head_size=head_size, ncols=ncols))

for ncols in [8, 16, 32, 64]:
    for ncols2 in [1, 2, 4, 8, 16, 32]:
        if ncols2 > ncols:
            continue
        ncols1 = ncols // ncols2
        with open(f"fattn-mma-f16-instance-ncols1_{ncols1}-ncols2_{ncols2}.cu", "w") as f:
            f.write(SOURCE_FATTN_MMA_START)

            for head_size_kq in HEAD_SIZES_KQ:
                if head_size_kq == 40:
                    continue
                if head_size_kq == 72:
                    continue
                if head_size_kq == 512 and ncols2 not in (2, 4, 8): # Gemma 4 (+ MTP)
                    continue
                # Skip compilation of unused ncols2 values for niche head sizes:
                if head_size_kq == 192 and ncols2 not in (8, 16): # MiMo-V2.5
                    continue
                if head_size_kq == 320 and ncols2 != 32: # Mistral Small 4
                    continue
                if head_size_kq == 576 and ncols2 not in (4, 16, 32): # Deepseek, GLM 4.7 Flash
                    continue
                if head_size_kq not in (192, 320, 576) and ncols2 in (16, 32):
                    continue
                head_size_v = HEAD_SIZES_V_OVERRIDE.get(head_size_kq, head_size_kq)
                f.write(SOURCE_FATTN_MMA_CASE.format(ncols1=ncols1, ncols2=ncols2, head_size_kq=head_size_kq, head_size_v=head_size_v))

for type in TYPES_MMQ:
    with open(f"mmq-instance-{get_short_name(type)}.cu", "w") as f:
        f.write(SOURCE_MMQ.format(type=type))

for type in range(1, 17):
    with open(f"mmf-instance-ncols_{type}.cu", "w") as f:
        f.write(SOURCE_MMF.format(type=type))
